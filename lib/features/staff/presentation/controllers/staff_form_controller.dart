import 'dart:io';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:intl/intl.dart';
import 'package:student_management/core/errors/error_handler.dart';
import 'package:student_management/features/staff/presentation/providers/staff_providers.dart';
import 'package:student_management/shared/models/staff.dart';

class StaffFormState {
  final bool isSubmitting;
  final bool isEditing;
  final String? staffId;
  final String? userId;
  final String? selectedDesignation;
  final File? avatarFile;
  final String? networkImageUrl;
  final String? errorMessage;
  final bool isSuccess;

  const StaffFormState({
    this.isSubmitting = false,
    this.isEditing = false,
    this.staffId,
    this.userId,
    this.selectedDesignation,
    this.avatarFile,
    this.networkImageUrl,
    this.errorMessage,
    this.isSuccess = false,
  });

  StaffFormState copyWith({
    bool? isSubmitting,
    bool? isEditing,
    String? staffId,
    String? userId,
    String? selectedDesignation,
    File? avatarFile,
    String? networkImageUrl,
    String? errorMessage,
    bool? isSuccess,
    bool clearError = false,
    bool clearAvatar = false,
  }) {
    return StaffFormState(
      isSubmitting: isSubmitting ?? this.isSubmitting,
      isEditing: isEditing ?? this.isEditing,
      staffId: staffId ?? this.staffId,
      userId: userId ?? this.userId,
      selectedDesignation: selectedDesignation ?? this.selectedDesignation,
      avatarFile: clearAvatar ? null : (avatarFile ?? this.avatarFile),
      networkImageUrl: networkImageUrl ?? this.networkImageUrl,
      errorMessage: clearError ? null : (errorMessage ?? this.errorMessage),
      isSuccess: isSuccess ?? this.isSuccess,
    );
  }
}

class StaffFormController extends AutoDisposeNotifier<StaffFormState> {
  @override
  StaffFormState build() {
    return const StaffFormState();
  }

  void init(Staff? initialStaff) {
    if (initialStaff != null) {
      state = StaffFormState(
        isEditing: true,
        staffId: initialStaff.id,
        userId: initialStaff.userId,
        selectedDesignation:
            initialStaff.designation.isNotEmpty
                ? initialStaff.designation
                : null,
        networkImageUrl: initialStaff.profileImageUrl,
      );
    } else {
      state = const StaffFormState();
    }
  }

  void setDesignation(String designation) {
    state = state.copyWith(selectedDesignation: designation, clearError: true);
  }

  void setAvatar(File? file) {
    state = state.copyWith(avatarFile: file, clearError: true);
  }

  Future<bool> createStaff({
    required String firstName,
    required String lastName,
    required String email,
    required String designation,
    required String dobString,
    required String address,
    required String phone,
  }) async {
    state = state.copyWith(isSubmitting: true, clearError: true);

    try {
      DateTime? parsedDob;
      if (dobString.isNotEmpty) {
        try {
          parsedDob = DateFormat('d/M/yyyy').parse(dobString);
        } catch (_) {
          parsedDob = DateTime.tryParse(dobString);
        }
      }

      final normalizedEmail = email.trim().toLowerCase();
      final yearPart =
          dobString.contains('/') ? dobString.split('/').last : '2000';
      final generatedPassword = '$firstName@$yearPart';

      final newStaff = Staff(
        id: '', // Generated by Auth
        userId: '',
        firstName: firstName.trim(),
        lastName: lastName.trim(),
        name: '$firstName $lastName'.trim(),
        designation: designation.trim(),
        email: normalizedEmail,
        phone: phone.trim(),
        address: address.trim(),
        dob: parsedDob,
      );

      final repository = ref.read(staffRepositoryProvider);
      await repository.createStaff(
        staff: newStaff,
        password: generatedPassword,
        avatarFile: state.avatarFile,
      );

      state = state.copyWith(isSubmitting: false, isSuccess: true);
      return true;
    } catch (e) {
      final failure = ErrorHandler.handleFailure(e);
      state = state.copyWith(
        isSubmitting: false,
        errorMessage: failure.message,
      );
      return false;
    }
  }

  Future<bool> updateStaff({
    required String firstName,
    required String lastName,
    required String email,
    required String designation,
    required String dobString,
    required String address,
    required String phone,
  }) async {
    if (state.staffId == null) {
      state = state.copyWith(errorMessage: 'Staff ID missing for update.');
      return false;
    }

    state = state.copyWith(isSubmitting: true, clearError: true);

    try {
      DateTime? parsedDob;
      if (dobString.isNotEmpty) {
        try {
          parsedDob = DateFormat('d/M/yyyy').parse(dobString);
        } catch (_) {
          parsedDob = DateTime.tryParse(dobString);
        }
      }

      final updatedStaff = Staff(
        id: state.staffId!,
        userId: state.userId ?? state.staffId!,
        firstName: firstName.trim(),
        lastName: lastName.trim(),
        name: '$firstName $lastName'.trim(),
        designation: designation.trim(),
        email: email.trim().toLowerCase(),
        phone: phone.trim(),
        address: address.trim(),
        profileImageUrl: state.networkImageUrl,
        dob: parsedDob,
      );

      final repository = ref.read(staffRepositoryProvider);
      await repository.updateStaff(
        staff: updatedStaff,
        avatarFile: state.avatarFile,
      );

      state = state.copyWith(isSubmitting: false, isSuccess: true);
      return true;
    } catch (e) {
      final failure = ErrorHandler.handleFailure(e);
      state = state.copyWith(
        isSubmitting: false,
        errorMessage: failure.message,
      );
      return false;
    }
  }
}
